import type {
  RemoteThreadInitializeResponse,
  RemoteThreadListAdapter,
  RemoteThreadListResponse,
  RemoteThreadMetadata,
} from "@assistant-ui/core";

export const createBackendThreadAdapter = (baseUrl = "/api"): RemoteThreadListAdapter => {
  return {
    async list(): Promise<RemoteThreadListResponse> {
      try {
        const res = await fetch(`${baseUrl}/chats`);
        if (!res.ok) {
          return { threads: [] };
        }
        const data = await res.json();
        return {
          threads: data.map((c: any) => ({
            remoteId: c.chat_id,
            title: c.name || "New Chat",
            status: c.is_archived ? ("archived" as const) : ("regular" as const),
            lastMessageAt: c.updated_at ? new Date(c.updated_at) : undefined,
          })),
        };
      } catch (err) {
        console.error("[assistant-ui] Error listing chats:", err);
        return { threads: [] };
      }
    },

    async initialize(threadId: string): Promise<RemoteThreadInitializeResponse> {
      try {
        const res = await fetch(`${baseUrl}/chats`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ chat_id: threadId, name: "New Chat" }),
        });
        const data = await res.json();
        return { remoteId: data.chat_id || threadId, externalId: undefined };
      } catch (err) {
        return { remoteId: threadId, externalId: undefined };
      }
    },

    async rename(remoteId: string, newTitle: string): Promise<void> {
      try {
        await fetch(`${baseUrl}/chats/${remoteId}`, {
          method: "PATCH",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ name: newTitle }),
        });
      } catch (err) {
        console.error("[assistant-ui] Error renaming chat:", err);
      }
    },

    async archive(remoteId: string): Promise<void> {
      try {
        await fetch(`${baseUrl}/chats/${remoteId}/archive`, {
          method: "POST",
        });
      } catch (err) {
        console.error("[assistant-ui] Error archiving chat:", err);
      }
    },

    async unarchive(remoteId: string): Promise<void> {
      try {
        await fetch(`${baseUrl}/chats/${remoteId}/unarchive`, {
          method: "POST",
        });
      } catch (err) {
        console.error("[assistant-ui] Error unarchiving chat:", err);
      }
    },

    async delete(remoteId: string): Promise<void> {
      try {
        await fetch(`${baseUrl}/chats/${remoteId}`, {
          method: "DELETE",
        });
      } catch (err) {
        console.error("[assistant-ui] Error deleting chat:", err);
      }
    },

    async fetch(threadId: string): Promise<RemoteThreadMetadata> {
      try {
        const res = await fetch(`${baseUrl}/chats/${threadId}`);
        if (!res.ok) {
          throw new Error(`Chat ${threadId} not found`);
        }
        const data = await res.json();
        return {
          remoteId: data.chat_id,
          title: data.name || "New Chat",
          status: data.is_archived ? ("archived" as const) : ("regular" as const),
          lastMessageAt: data.updated_at ? new Date(data.updated_at) : undefined,
        };
      } catch (err) {
        return {
          remoteId: threadId,
          title: "New Chat",
          status: "regular" as const,
        };
      }
    },

    async generateTitle(remoteId: string) {
      try {
        // Poll briefly if title was just generated by the backend
        for (let i = 0; i < 3; i++) {
          const res = await fetch(`${baseUrl}/chats/${remoteId}`);
          if (res.ok) {
            const data = await res.json();
            if (data.name && data.name !== "New Chat") {
              return new ReadableStream({
                start(controller) {
                  controller.enqueue(data.name);
                  controller.close();
                },
              }) as any;
            }
          }
          await new Promise((r) => setTimeout(r, 600));
        }
      } catch (e) {
        console.error("[assistant-ui] Error generating title:", e);
      }
      return new ReadableStream({
        start(controller) {
          controller.close();
        },
      }) as any;
    },
  };
};

export const backendThreadAdapter = createBackendThreadAdapter();
